"""
SupeRR Selector — Pressure Performance Intelligence
FastAPI Web Server & REST API Adapter
Serves the web platform and provides endpoints connected to SupeRR_ClutchML.
"""

import os
import json
from typing import Optional, List
from fastapi import FastAPI, HTTPException, Query
from fastapi.staticfiles import StaticFiles
from fastapi.responses import FileResponse, JSONResponse
from fastapi.middleware.cors import CORSMiddleware

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_FILE = os.path.join(BASE_DIR, "data", "platform_data.json")
STATIC_DIR = os.path.join(BASE_DIR, "static")

# Load pre-compiled platform data generated by SupeRR-ClutchML
if not os.path.exists(DATA_FILE):
    raise FileNotFoundError(f"Platform data not found at {DATA_FILE}. Run build_platform_data.py first.")

with open(DATA_FILE, "r", encoding="utf-8") as f:
    PLATFORM_DATA = json.load(f)

app = FastAPI(
    title="SupeRR Selector — Pressure Performance Intelligence",
    description="Cricket Analytics Engine powered by SupeRR-ClutchML",
    version="2.4.0"
)

# Enable CORS
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# ----------------- API Endpoints -----------------

@app.get("/api/meta")
def get_meta():
    """Returns model metadata, dataset coverage, and version info."""
    return PLATFORM_DATA.get("meta", {})

@app.get("/api/overview")
def get_overview():
    """Returns overview statistics, featured players, and pressure distributions."""
    return PLATFORM_DATA.get("overview", {})

@app.get("/api/batters")
def get_batters(
    role: Optional[str] = Query(None, description="Filter by role: Top Order (1-3), Middle Order (4-5), Lower Order / Finisher (6+)"),
    top10_only: bool = Query(False, description="Filter strictly to top 10 role-balanced batters"),
    search: Optional[str] = Query(None, description="Search by player name or franchise"),
    min_balls: int = Query(75, description="Minimum pressure balls faced")
):
    """Returns eligible batters with optional filtering, sorting, and search."""
    batters = PLATFORM_DATA.get("batters", [])
    res = []
    for b in batters:
        if b["p_balls"] < min_balls:
            continue
        if top10_only and not b.get("is_top10", False):
            continue
        if role and role.lower() not in b.get("role", "").lower():
            continue
        if search:
            q = search.lower()
            if q not in b["player_name"].lower() and q not in b.get("team", "").lower():
                continue
        res.append(b)
    return res

@app.get("/api/bowlers")
def get_bowlers(
    top10_only: bool = Query(False, description="Filter strictly to top 10 bowlers"),
    search: Optional[str] = Query(None, description="Search by bowler name or franchise"),
    min_balls: int = Query(100, description="Minimum pressure balls bowled")
):
    """Returns eligible bowlers with optional filtering, sorting, and search."""
    bowlers = PLATFORM_DATA.get("bowlers", [])
    res = []
    for bw in bowlers:
        if bw["p_balls"] < min_balls:
            continue
        if top10_only and not bw.get("is_top10", False):
            continue
        if search:
            q = search.lower()
            if q not in bw["player_name"].lower() and q not in bw.get("team", "").lower():
                continue
        res.append(bw)
    return res

@app.get("/api/player/{player_id}")
def get_player_profile(player_id: str):
    """Returns detailed player profile, whether batter or bowler."""
    for b in PLATFORM_DATA.get("batters", []):
        if str(b["player_id"]) == str(player_id):
            return {"type": "batter", "data": b}
    for bw in PLATFORM_DATA.get("bowlers", []):
        if str(bw["player_id"]) == str(player_id):
            return {"type": "bowler", "data": bw}
    raise HTTPException(status_code=404, detail="Player not found in eligible database")

@app.get("/api/why-player/{player_id}")
def get_why_player(player_id: str):
    """Returns the 6-point deterministic analytical explanation for a player."""
    for b in PLATFORM_DATA.get("batters", []):
        if str(b["player_id"]) == str(player_id):
            return {
                "player_id": player_id,
                "player_name": b["player_name"],
                "role": b["role"],
                "type": "batter",
                "clutch_score": b["clutch_score"],
                "rank": b["rank"],
                "explanation": b.get("why_this_player", {})
            }
    for bw in PLATFORM_DATA.get("bowlers", []):
        if str(bw["player_id"]) == str(player_id):
            return {
                "player_id": player_id,
                "player_name": bw["player_name"],
                "role": "Bowler",
                "type": "bowler",
                "clutch_score": bw["clutch_score"],
                "rank": bw["rank"],
                "explanation": bw.get("why_this_player", {})
            }
    raise HTTPException(status_code=404, detail="Player not found")

@app.get("/api/compare")
def compare_players(ids: str = Query(..., description="Comma-separated player IDs (2 or 3)")):
    """Compares 2 or 3 players side-by-side."""
    id_list = [i.strip() for i in ids.split(",") if i.strip()]
    if len(id_list) < 2 or len(id_list) > 3:
        raise HTTPException(status_code=400, detail="Must provide 2 or 3 player IDs to compare")

    results = []
    all_players = PLATFORM_DATA.get("batters", []) + PLATFORM_DATA.get("bowlers", [])
    for pid in id_list:
        match = next((p for p in all_players if str(p["player_id"]) == pid), None)
        if match:
            results.append(match)
        else:
            raise HTTPException(status_code=404, detail=f"Player ID {pid} not found")

    return results

@app.get("/api/auction-targets")
def get_auction_targets():
    """Returns the alternate list: Auction Target Radar for franchise scouts."""
    return PLATFORM_DATA.get("auction_targets", [])

@app.get("/api/matches")
def get_matches():
    """Returns curated landmark crunch matches for Match Explorer."""
    return PLATFORM_DATA.get("landmark_matches", [])

@app.get("/api/match/{match_id}")
def get_match_detail(match_id: str):
    """Returns ball-by-ball timeline and pressure progression for a match."""
    for m in PLATFORM_DATA.get("landmark_matches", []):
        if str(m["match_id"]) == str(match_id):
            return m
    raise HTTPException(status_code=404, detail="Match not found in landmark database")

# Mount static files
app.mount("/static", StaticFiles(directory=STATIC_DIR), name="static")

@app.get("/")
def serve_home():
    """Serves the main single page web application."""
    index_path = os.path.join(STATIC_DIR, "index.html")
    if os.path.exists(index_path):
        return FileResponse(index_path)
    return {"message": "SupeRR Selector API is active. Web UI index.html not yet built."}

